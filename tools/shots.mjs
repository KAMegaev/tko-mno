import { chromium } from 'playwright';
import path from 'node:path';
const root = path.resolve('.');
const dir = process.env.SHOTS || '/tmp/shots';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const p = await b.newPage({ viewport: { width: 1180, height: 900 }, deviceScaleFactor: 2 });
await p.goto(process.env.BASE || 'http://127.0.0.1:8765', { waitUntil: 'networkidle' });
await p.screenshot({ path: `${dir}/1-files.png` });
await p.setInputFiles('[data-drop="registry"] input', path.join(root, 'tools/testdata/registry.xlsx'));
await p.setInputFiles('[data-drop="template"] input', path.join(root, 'tools/testdata/template.xlsx'));
await p.screenshot({ path: `${dir}/1-files-set.png` });
await p.click('#btn-parse');
await p.waitForSelector('.step[data-step="2"].is-current');
await p.screenshot({ path: `${dir}/2-columns.png`, fullPage: true });
await p.click('#btn-to-mo');
await p.waitForSelector('.step[data-step="3"].is-current');
await p.screenshot({ path: `${dir}/3-mo.png`, fullPage: true });
await p.click('#btn-build');
await p.waitForSelector('.step[data-step="4"].is-current');
await p.screenshot({ path: `${dir}/4-report.png`, fullPage: true });
await b.close();
console.log('готово');
