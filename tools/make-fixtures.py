#!/usr/bin/env python3
"""Генерирует небольшие тестовые файлы, повторяющие структуру настоящих.

Настоящая выгрузка реестра по региону в репозиторий не попадает: здесь
вымышленные муниципальные образования и специально расставленные особые случаи.

    pip install openpyxl && python3 tools/make-fixtures.py
"""
import os
from openpyxl import Workbook
from openpyxl.utils import get_column_letter

HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'testdata')

SUBJECT = 'Тестовая область'
# Наименования шаблона; «(архив)» намеренно отсутствует в реестре.
TEMPLATE_MO = [
    'Первомайский муниципальный район',
    'Приозёрный муниципальный район',
    'Городской округ город Тестоград',
    'Городской округ посёлок Ясный (ЗАТО)',
    'муниципальный округ посёлок Северный',
    'Заречный муниципальный район (архив)',
]
# Как те же образования названы в реестре: точно, без слов-типов и с опечаткой.
REGISTRY_MO = {
    'Первомайский муниципальный район': 'Первомайский муниципальный район',
    'Приозёрный муниципальный район': 'Приозерный район',
    'Городской округ город Тестоград': 'Городской округ город Тестоград',
    'Городской округ посёлок Ясный (ЗАТО)': 'ЗАТО посёлок Ясный',
    'муниципальный округ посёлок Северный': 'Северный муниципальный округ',
}


def build_template(path):
    wb = Workbook()
    ws = wb.active
    ws.title = 'Общие сведения'
    ws['A1'] = 'Субъект РФ'
    ws['B1'] = 'Муниципальное образование'
    ws['C1'] = 'Количество МНО'
    ws['D1'] = 'Количество МНО с раздельным сбором'
    ws['E1'] = 'Количество контейнеров'
    ws['I1'] = 'Потребность в организации новых МНО'
    ws['J1'] = 'Потребность в организации новых МНО с раздельным сбором'
    for col, name in zip('EFGH', ['Смешанные ТКО', 'Раздельный сбор', 'КГО', 'Иное']):
        ws[f'{col}2'] = name
    for col in 'ABCDIJ':
        ws.merge_cells(f'{col}1:{col}3')
    for col in 'EFGH':
        ws.merge_cells(f'{col}2:{col}3')
    ws.merge_cells('E1:H1')
    for col in 'ABCDEFGHIJ':
        ws[f'{col}4'] = 'список' if col in 'AB' else 'число'
        ws[f'{col}5'] = 'обязательное поле'
    for i, name in enumerate(TEMPLATE_MO):
        ws.cell(6 + i, 1, SUBJECT)
        ws.cell(6 + i, 2, name)

    for title, header, values in [
        ('Субъекты РФ', ['Субъект РФ'], [[SUBJECT]]),
        ('Муниципальные образования', ['Субъект РФ', 'Муниципальные образования'],
         [[SUBJECT, n] for n in TEMPLATE_MO]),
    ]:
        sheet = wb.create_sheet(title)
        sheet.append(header)
        for row in values:
            sheet.append(row)
    wb.save(path)


GROUPS = [
    ('Контейнеры (бункеры) для совместного накопления ТКО', 13),
    ('Контейнеры (бункеры) для раздельного накопления ТКО', 18),
    ('Контейнеры (бункеры) для крупногабаритных отходов', 23),
    ('Иные контейнеры (бункеры)', 28),
]
SUB = ['Количество контейнеров (бункеров), шт.', 'Цвет контейнера (бункера)',
       'Описание цветовой индикации', 'Вид и (или) группа отходов, складируемых в контейнер (бункер)',
       'Объем контейнера (бункера), м³']


def build_registry(path):
    wb = Workbook()
    ws = wb.active
    ws.title = 'Реестр МНО'
    top = ['Субъект РФ', 'Муниципальное образование', 'Населенный пункт',
           'Категория места (площадки) накопления ТКО', 'Покрытие основания',
           'Способ складирования крупногабаритных ТКО',
           'Площадь места (площадки) накопления ТКО, м2',
           'Наличие раздельного накопления ТКО',
           'Вхождение в состав общего имущества многоквартирного дома',
           'Наличие ограждения\xa0', 'Общее количество контейнеров (бункеров), шт.',
           'Общий объем контейнеров (бункеров), м³']
    for i, value in enumerate(top, 1):
        ws.cell(2, i, value)
    for name, start in GROUPS:
        ws.cell(2, start, name)
        ws.merge_cells(start_row=2, start_column=start, end_row=2, end_column=start + 4)
        for j, sub in enumerate(SUB):
            ws.cell(3, start + j, sub)
    ws.cell(2, 33, 'Зона деятельности')

    # (МО-шаблон, всего, смешанные, раздельные, КГО, иные, отметка «раздельное»)
    plan = []
    for mo in ['Первомайский муниципальный район'] * 5:
        plan.append((mo, 2, 2, 0, 0, 0, 'Нет'))
    plan.append(('Первомайский муниципальный район', 3, 0, 0, 0, 0, 'Нет'))   # без разбивки
    plan.append(('Первомайский муниципальный район', 4, 2, 2, 0, 0, 'Да'))
    for mo in ['Приозёрный муниципальный район'] * 3:
        plan.append((mo, 1, 1, 0, 0, 0, 'Нет'))
    plan.append(('Приозёрный муниципальный район', 5, 0, 0, 0, 0, 'Да'))      # без разбивки, отметка Да
    plan.append(('Городской округ город Тестоград', 6, 4, 2, 0, 0, 'Нет'))    # контейнеры есть, отметки нет
    plan.append(('Городской округ город Тестоград', 8, 6, 0, 1, 1, 'Нет'))
    plan.append(('Городской округ посёлок Ясный (ЗАТО)', 2, 2, 0, 0, 0, 'Нет'))
    plan.append(('муниципальный округ посёлок Северный', 3, 1, 1, 1, 0, 'Да'))

    row = 4
    for mo, total, mixed, sep, bulky, other, flag in plan:
        ws.cell(row, 1, SUBJECT)
        ws.cell(row, 2, REGISTRY_MO[mo])
        ws.cell(row, 3, 'Сельское поселение')
        ws.cell(row, 4, 'Контейнерная площадка')
        ws.cell(row, 8, flag)
        # Числа в выгрузке приходят текстом — так же, как в настоящем реестре.
        ws.cell(row, 11, str(total))
        for value, (_, start) in zip([mixed, sep, bulky, other], GROUPS):
            if value:
                ws.cell(row, start, str(value))
        row += 1
    wb.save(path)


if __name__ == '__main__':
    os.makedirs(HERE, exist_ok=True)
    build_template(os.path.join(HERE, 'template.xlsx'))
    build_registry(os.path.join(HERE, 'registry.xlsx'))
    print('готово:', HERE)
